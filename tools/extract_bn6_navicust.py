#!/usr/bin/env python3
"""Builds data/bn6-navicust.mjs from the two BN6 US ROMs (Falzar and Gregar).

Numbers and names only (no graphics). Locations found with the dism-exe/bn6f disassembly (Falzar), values read
from the ROMs; Gregar's copies sit at +0x1DE0 (data) and the names at 0x73C98C.

  StructArr_813944C: 16 bytes per program variant (program << 2 | variant), read by sub_813B780:
    +0 exclusive group (two programs of one nonzero group: only the first applies, applyNavicustPrograms_813C684)
    +1 1 = Plus Part (works off the command line; sub_813BC1C / sub_813BC98)
    +2 1 = program exists
    +3 colour of this variant (0 = the variant doesn't exist): 1 white 2 yellow 3 pink 4 red 5 blue 6 green
    +4 bug type caused when misplaced or touching a part of the same colour (counters at Unk200431c)
    +8 / +12 pointers to the 7×7 shape and its compressed shape (event flag 0x2660 + part once its code is entered)
  Board layouts byte_813B1EC / 813B2CD / 813B3AE (sub_813B9E0, by ExpMemry key item 0x71 count): 15×15 bytes, the
    7×7 grid at (5,5); 1 = usable, 3 = frame (placing there is allowed but bugs), 0 = off the board.
  Names: text archive at 0x73EA50 (Falzar; pointer at 0x8042078), entries 0–46.
Usage: python3 tools/extract_bn6_navicust.py FALZAR.gba GREGAR.gba > data/bn6-navicust.mjs
"""
import json, struct, sys

PARTS, LAYOUTS, NAMES = 0x13944C, (0x13B1EC, 0x13B2CD, 0x13B3AE), 0x73EA50
COUNT = 47  # program 0 is "None"; 1–46 are the programs (navicust_jt_NCPs)
TEXT = {0: ' ', 0x9E: '+', 0x98: '-', 0xA6: '.'}
for i in range(10): TEXT[1 + i] = str(i)
for i in range(26): TEXT[0x0B + i] = chr(65 + i); TEXT[0x26 + i] = chr(97 + i)


def names(b, base):
    out = []
    for k in range(COUNT):
        o = base + struct.unpack_from('<H', b, base + 2 * k)[0]
        e = b.index(b'\xe6', o)
        out.append(''.join(TEXT.get(x, '?') for x in b[o:e]))
    return out


def shape(b, ptr):
    a = ptr - 0x8000000
    return [list(b[a + 7 * r:a + 7 * r + 7]) for r in range(7)]


def parts(b, base, nm):
    out = []
    for p in range(1, COUNT):
        variants = []
        for v in range(4):
            r = b[base + 16 * (4 * p + v):base + 16 * (4 * p + v) + 16]
            if r[3]: variants.append({'variant': v, 'color': r[3]})
        r = b[base + 16 * 4 * p:base + 16 * 4 * p + 16]
        s1, s2 = struct.unpack_from('<II', r, 8)
        out.append({'id': p, 'name': nm[p], 'group': r[0], 'plus': r[1] == 1, 'bug': r[4], 'variants': variants,
                    'shape': shape(b, s1), 'compressed': shape(b, s2)})
    return out


f, g = (open(p, 'rb').read() for p in sys.argv[1:3])
assert f[0xAC:0xB0] == b'BR6E' and g[0xAC:0xB0] == b'BR5E', 'expects Falzar then Gregar (US)'
pf = parts(f, PARTS, names(f, NAMES))
pg = parts(g, PARTS + 0x1DE0, names(g, 0x73C98C))
assert pf == pg, 'program data differs between versions'
layouts = [[list(f[a + 15 * (5 + y) + 5:a + 15 * (5 + y) + 12]) for y in range(7)] for a in LAYOUTS]
assert layouts == [[list(g[a + 0x1DE0 + 15 * (5 + y) + 5:a + 0x1DE0 + 15 * (5 + y) + 12]) for y in range(7)] for a in LAYOUTS]
data = {'source': 'BN6 US ROMs: StructArr_813944C (programs), byte_813B1EC/813B2CD/813B3AE (board layouts), names at 0x73EA50 '
                  '(dism-exe/bn6f labels, values read from the ROM; identical in both versions)',
        'commandLine': 3, 'parts': pf, 'layouts': layouts}
print('// Generated by tools/extract_bn6_navicust.py from the ROMs. Numbers and names only.')
print('export default ' + json.dumps(data, separators=(',', ':')) + ';')
