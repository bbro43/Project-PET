#!/usr/bin/env python3
"""Builds data/bn6-chips.mjs from the two BN6 US ROMs (Falzar and Gregar).

Reads only numbers and names (no graphics). Locations were found with the dism-exe/bn6f
disassembly (Falzar) and confirmed in both ROMs:
  ChipDataArr 0x21DA8: 411 records of 0x2C bytes (chip_data_struct)
  chip names: two text archives whose pointers sit at 0x27D2C / 0x27D30
  FolderTable 0x8137868 → 6 folders of 30 u16 entries (id = v & 0x1FF, code = v >> 9)
Usage: python3 tools/extract_bn6_chips.py FALZAR.gba GREGAR.gba > data/bn6-chips.mjs
"""
import json, struct, sys

TABLE, COUNT, SIZE = 0x21DA8, 411, 0x2C
NAME_PTRS = 0x27D2C
FOLDER_TABLE = 0x137868
ELEMENTS = ['none', 'fire', 'aqua', 'elec', 'wood']
CHIP_ELEMENTS = ['fire', 'aqua', 'elec', 'wood', 'plus', 'sword', 'cursor', 'obstacle', 'wind', 'break', 'none']
CLASSES = ['standard', 'mega', 'giga', 'secret']
CODES = [chr(65 + i) for i in range(26)] + ['*']
# Text encoding (subset of the bn6f charmap): letters, digits and the symbols chip names use.
TEXT = {0: ' ', 0x25: '*', 0x40: 'RV', 0x41: 'BX', 0x42: 'EX', 0x43: 'SP', 0x44: 'FZ', 0x98: '-', 0x99: '×', 0x9A: '=', 0x9B: ':', 0x9C: '%', 0x9D: '?', 0x9E: '+'}
for i in range(10): TEXT[0x01 + i] = str(i)
for i in range(26): TEXT[0x0B + i] = chr(65 + i); TEXT[0x26 + i] = chr(97 + i)


def names(b):
    out = []
    for k in range(2):
        base = struct.unpack_from('<I', b, NAME_PTRS + 4 * k)[0] - 0x08000000
        n = struct.unpack_from('<H', b, base)[0] // 2
        for off in struct.unpack_from(f'<{n}H', b, base):
            o = base + off; e = b.index(b'\xe6', o)
            out.append(''.join(TEXT.get(x, '?') for x in b[o:e]))
    return out


def chips(b):
    nm = names(b)
    out = []
    for i in range(COUNT):
        o = TABLE + i * SIZE
        r = b[o:o + SIZE]
        codes = [CODES[c] for c in r[0:4] if c != 0xFF]
        power = struct.unpack_from('<H', r, 0x1A)[0]
        # Power ≥ 1001 is a code (sub_8010C76): 11 tiers at 0x20E54 + 22·(power − 1001), picked by a saved
        # battle-time record (unk_20018C0) against the thresholds at 0x10CB8; tier 0 = no record.
        tiers = list(struct.unpack_from('<11H', b, 0x20E54 + 22 * (power - 1001))) if 1001 <= power <= 1018 else None
        out.append({
            'id': i, 'name': nm[i] if i < len(nm) else '', 'codes': codes,
            'element': ELEMENTS[r[4]] if r[4] < 5 else r[4], 'icon': CHIP_ELEMENTS[r[6]] if r[6] < len(CHIP_ELEMENTS) else r[6],
            'class': CLASSES[r[7]] if r[7] < 4 else r[7], 'mb': r[8], 'rarity': r[5],
            'damage': struct.unpack_from('<H', r, 0x1A)[0], 'flags': r[9], 'family': r[0xB], 'subfamily': r[0xC],
            'params': list(r[0x10:0x14]), 'abc': struct.unpack_from('<H', r, 0x18)[0], 'order': struct.unpack_from('<H', r, 0x1C)[0], 'lockout': r[0x14], 'library': r[0x15], 'darkChip': r[0x1F] if r[0x1F] != 0xFF else None, 'tiers': tiers,
        })
    return out


def folders(b):
    out = []
    for k in range(6):
        p = struct.unpack_from('<I', b, FOLDER_TABLE + 4 * k)[0] - 0x08000000
        out.append([[v & 0x1FF, CODES[v >> 9]] for v in struct.unpack_from('<30H', b, p)])
    return out


f, g = (open(p, 'rb').read() for p in sys.argv[1:3])
assert f[0xAC:0xB0] == b'BR6E' and g[0xAC:0xB0] == b'BR5E', 'expects Falzar then Gregar (US)'
cf, cg = chips(f), chips(g)
diff = {c['id']: c for c, d in zip(cg, cf) if c != d}
data = {'source': 'BN6 US ROMs: ChipDataArr 0x21DA8, names via 0x27D2C, FolderTable 0x137868 (dism-exe/bn6f labels, values read from the ROM)',
        'chips': cf, 'gregar': diff, 'folders': folders(f)}
print('// Generated by tools/extract_bn6_chips.py from the ROMs. Numbers and names only.')
print('export default ' + json.dumps(data, separators=(',', ':')) + ';')
